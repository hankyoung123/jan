import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

import openapiTS, { astToString } from "openapi-typescript";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, "..");
const openapiPath = resolve(repositoryRoot, "packages/contracts/openapi.json");
const generatedPath = resolve(
  repositoryRoot,
  "packages/contracts/src/generated.ts",
);

const exportResult = spawnSync(
  "uv",
  [
    "run",
    "--project",
    "apps/story-engine",
    "python",
    "-m",
    "story_engine.contracts",
    "--output",
    openapiPath,
  ],
  {
    cwd: repositoryRoot,
    stdio: "inherit",
  },
);

if (exportResult.status !== 0) {
  process.exit(exportResult.status ?? 1);
}

const schema = JSON.parse(readFileSync(openapiPath, "utf8"));
const declarations = await openapiTS(schema);
const banner = [
  "/* eslint-disable */",
  "// Generated by pnpm contracts:generate. Do not edit manually.",
  "",
].join("\n");

mkdirSync(dirname(generatedPath), { recursive: true });
writeFileSync(generatedPath, `${banner}${astToString(declarations)}`, "utf8");
